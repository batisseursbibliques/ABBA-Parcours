export function listePays(lang) {
  let dn = null;
  try { dn = new Intl.DisplayNames([lang === "en" ? "en" : "fr"], { type: "region" }); } catch (e) {}
  const items = CODES_PAYS.map((c) => ({ code: c, nom: (dn && dn.of(c)) || c }));
  const coll = new Intl.Collator(lang === "en" ? "en" : "fr");
  items.sort((a, b) => coll.compare(a.nom, b.nom));
  const bj = items.findIndex((x) => x.code === "BJ");
  if (bj > 0) items.unshift(items.splice(bj, 1)[0]);   // le Bénin en premier
  return items;
}
